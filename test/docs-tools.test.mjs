import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generateToolsMarkdown, readToolsDoc } from '../scripts/docs-tools.ts';

test('docs/tools.md matches the live tools/list output generated by scripts/docs-tools.ts', async () => {
  const expected = await generateToolsMarkdown();
  const actual = readToolsDoc();
  assert.equal(actual, expected, 'docs/tools.md is out of date; run `npm run docs:tools`.');
});
