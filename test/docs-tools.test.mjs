import { test } from 'node:test';
import assert from 'node:assert/strict';
import { determineAvailability, generateToolsMarkdown, readToolsDoc } from '../scripts/docs-tools.ts';

test('docs/tools.md matches the live tools/list output generated by scripts/docs-tools.ts', async () => {
  const expected = await generateToolsMarkdown();
  const actual = readToolsDoc();
  assert.equal(actual, expected, 'docs/tools.md is out of date; run `npm run docs:tools`.');
});

test('docs availability rejects unexpected tools in the base set', () => {
  assert.throws(
    () =>
      determineAvailability('unexpected_tool', {
        base: new Set(['unexpected_tool']),
        crmOnly: new Set(),
        chatOnly: new Set(),
      }),
    /Unexpected base tool: unexpected_tool/,
  );
});
